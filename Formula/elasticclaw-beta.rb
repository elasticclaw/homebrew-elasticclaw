    on_intel do
      url "https://github.com/elasticclaw/elasticclaw/releases/download/#{version}/elasticclaw-darwin-amd64"
      sha256 "5bf0d3980c293b812e62a3246527baf92f08c66f0ef36741ca0a6a987b189742"
    end
  end

  on_linux do
